def apply_to_app(app) -> None:
    current = getattr(app, "SYSTEM_INSTRUCTION", "")
    if LANGUAGE_POLICY_MARKER not in current:
        app.SYSTEM_INSTRUCTION = current + "\n\n" + LANGUAGE_POLICY_MARKER + "\n" + SYRIAN_LANGUAGE_GUIDE
